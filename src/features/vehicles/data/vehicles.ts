export type DemoVehicle = Omit<Vehicle, "frames" | "is360Enabled">;

function images(slug: string, name: string, count: number): VehicleImage[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `${slug}-${index + 1}`,
    src: `/images/vehicles/${slug}/${String(index + 1).padStart(2, "0")}.jpg`,
    alt: `${name}, view ${index + 1}`,
    width: 1600,
    height: 1000,
    role: (index === 0 ? "hero" : "gallery") as ImageRole,
  }));
}

